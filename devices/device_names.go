// ManufacturerName returns the human readable name for an ANT+ manufacturer
// ID (common data page 80). Unknown IDs are rendered as "Unknown (N)".
// This addresses openant issue #69 (end device names).
func ManufacturerName(id int) string {
	if name, ok := manufacturerNames[id]; ok {
		return name
	}
	return fmt.Sprintf("Unknown (%d)", id)
}
